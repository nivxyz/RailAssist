const DICTS: Record<LangCode, Dict> = { en, hi, ta, kn, te, bn, mr };

export function t(lang: LangCode, key: TKey, params?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? en[key];
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

const NEED_KEYS: Record<NeedType, TKey> = {
  wheelchair: "needWheelchair",
  porter: "needPorter",
  battery_car: "needBatteryCar",
  lower_berth: "needLowerBerth",
  meal: "needMeal",
  medical: "needMedical",
  escort: "needEscort",
  other: "needOther",
};

export function needLabel(lang: LangCode, type: NeedType): string {
  return t(lang, NEED_KEYS[type]);
}

export function langName(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.english ?? "English";
}

export function isLang(x: unknown): x is LangCode {
  return typeof x === "string" && LANGUAGES.some((l) => l.code === x);
}
